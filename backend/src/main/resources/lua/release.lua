-- ============================================================================
-- 10.3 放号初始化桶(原子)—— 04 §四 逐字落地
--
-- 返回值:恒 1
--
-- ⚠️ **必须在 `released 0→1` 的 CAS 成功之后才执行**(07 §3.1)。
--    本脚本用 SET 覆盖写,重跑得同一结果 —— 看似幂等,但**重跑会覆盖掉已被抢掉的余量**,
--    等于凭空造出库存。CAS 受影响 0 行即说明已放过号,**绝不能再跑本脚本**。
--    这是"锁减概率、CAS 保正确"在放号链路的落点。
--
-- ⚠️ ARGV[1..N] 是**逐桶**的值,不是"每桶同一值"。按 03 §4.2 的余数规则:
--    base = capacity / n,rem = capacity % n,**前 rem 个桶各多 1**。
--    (capacity=55, bucket=10 → 6,6,6,6,6,5,5,5,5,5,Σ=55)
--    若给所有桶传同一个值,Σ桶初值 < capacity,库存不变量 C = A + R + V + X
--    会永久带一个固定差 —— 而对账每轮都报同样的 diff,查不出原因。
--
-- ⚠️ 桶 key 必须带 EX:不设则 key 永久驻留,过期场次的余量长期占内存,
--    且被库存对账当作有效数据比对。
--
-- KEYS[1..N] = 桶 keys(按 bucket_no 0..N-1 顺序传入)
-- ARGV[1..N] = 各桶初始值,与 KEYS 一一对应
-- ARGV[N+1]  = slot_id
-- ARGV[N+2]  = bucket_ttl(秒, = slot_date 当日结束 − now)
-- ============================================================================

local n = #KEYS
for i = 1, n do
    redis.call('SET', KEYS[i], ARGV[i], 'EX', ARGV[n + 2])
end
redis.call('DEL', 'slot:full:'..ARGV[n + 1])   -- 清约满标记(此时段开始可约了)
return 1
